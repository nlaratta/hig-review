/**
 * docs/RULES.md is generated from the registry and the heuristic list (`npm run docs:rules`), and a
 * unit test fails when the committed file differs, so paraphrases in the docs can't drift.
 */

import { RULES } from './registry.js';
import { HEURISTICS } from '../swift/heuristics.js';

const PAGE_NAMES: Record<string, string> = {
  accessibility: 'Accessibility',
  buttons: 'Buttons',
  typography: 'Typography',
  color: 'Color',
  'dark-mode': 'Dark Mode',
  voiceover: 'VoiceOver',
  layout: 'Layout',
  'tab-bars': 'Tab bars',
  toolbars: 'Toolbars',
  alerts: 'Alerts',
  'action-sheets': 'Action sheets',
  sheets: 'Sheets',
  'lists-and-tables': 'Lists and tables',
  toggles: 'Toggles',
  'segmented-controls': 'Segmented controls',
  'text-fields': 'Text fields',
  gestures: 'Gestures',
  'sf-symbols': 'SF Symbols',
  'app-icons': 'App icons',
  onboarding: 'Onboarding',
  launching: 'Launching',
};

const BASE = 'https://developer.apple.com/design/human-interface-guidelines/';
const cell = (s: string) => s.replace(/\|/g, '\\|');

export function renderRulesDoc(): string {
  const lines = [
    '# Rules and checks',
    '',
    '<!-- Generated by `npm run docs:rules` from src/rules/registry.ts and src/swift/heuristics.ts. Do not edit by hand. -->',
    '',
    'Every rule below points to a Human Interface Guidelines page and was confirmed on the live page when it was added. At runtime, `hig_checklist`, `review_swiftui` and `check_contrast` fetch that page again and quote the one sentence (or table row) the rule is based on. If Apple has reworded it, or the locator matches more than one sentence, the citation comes back as `verified: false`, with no quote. A citation matched against an expired cached copy, because Apple could not be reached, is also unverified and marked `source: "stale-cache"`.',
    '',
    '`npm run smoke` re-checks every rule against the live site. Each rule\'s locator must match exactly one sentence. Its platforms must be covered by the page\'s supported platforms and by any platform heading above the sentence. Its numbers must appear in the cited text.',
    '',
    'The "What to look for" text is our own paraphrase. It keeps Apple\'s hedges ("consider", "prefer", "ideally"). Apple\'s wording appears only in the live quotes. The registry is in [`src/rules/registry.ts`](../src/rules/registry.ts).',
    '',
    '## Review rules',
    '',
    '| Rule | Severity | Platforms | What to look for | HIG page |',
    '| --- | --- | --- | --- | --- |',
    ...RULES.map(
      (r) =>
        `| \`${r.id}\` | ${r.severity} | ${r.platforms === 'all' ? 'all' : r.platforms.join(', ')} | ${cell(r.check)} | [${PAGE_NAMES[r.source.slug] ?? r.source.slug}](${BASE}${r.source.slug}) |`
    ),
    '',
    '## SwiftUI heuristics (`review_swiftui`)',
    '',
    '`<platform>` means the per-platform rule variant, for example `controls.size.macos`. iPadOS uses the iOS rules. Before any check runs, the code is masked: comments and string contents are blanked, and `#if os(...)` branches that don\'t apply to the target platform are removed.',
    '',
    '| Check | Rule | What it flags | Known false positives |',
    '| --- | --- | --- | --- |',
    ...HEURISTICS.map((h) => `| \`${h.id}\` | ${h.ruleIds.map((x) => '`' + x + '`').join(', ')} | ${cell(h.description)} | ${cell(h.falsePositives)} |`),
    '',
  ];
  return lines.join('\n');
}
