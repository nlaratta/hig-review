#!/usr/bin/env node
/**
 * Bundle the server into one dependency-free ESM file, plugin/server.mjs, for the Claude Code
 * plugin. The file is committed on purpose so the plugin works from a plain git clone without
 * `npm install`; CI rebuilds it and fails if the committed copy is stale.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const result = await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, 'src/index.ts')],
  outfile: path.join(root, 'plugin/server.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'eof',
  sourcemap: false,
  metafile: true,
  minify: false,
  logLevel: 'warning',
  // Some dependencies are CommonJS and call require(); give the ESM bundle a real one.
  banner: {
    js: [
      '// hig-review: bundled MCP server. Generated by `npm run bundle` from src/; do not edit by hand.',
      '// Bundled third-party packages and their licenses: see THIRD_PARTY_LICENSES.txt next to this file.',
      "import { createRequire as __hrCreateRequire } from 'node:module';",
      'const require = __hrCreateRequire(import.meta.url);',
    ].join('\n'),
  },
});

// Licenses of every package that ended up in the bundle (esbuild drops most license comments).
const pkgDirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (m) pkgDirs.add(m[1]);
}
const sections = [...pkgDirs].sort().map((dir) => {
  const abs = path.join(root, dir);
  const meta = JSON.parse(fs.readFileSync(path.join(abs, 'package.json'), 'utf8'));
  const licenseFile = fs.readdirSync(abs).find((f) => /^(license|licence|copying)(\.|$)/i.test(f));
  const text = licenseFile ? fs.readFileSync(path.join(abs, licenseFile), 'utf8').trim() : `License: ${meta.license ?? 'unknown'} (no license file in the package)`;
  return `${meta.name}@${meta.version} (${meta.license ?? 'unknown'})\n${'-'.repeat(72)}\n${text}\n`;
});
fs.writeFileSync(
  path.join(root, 'plugin/THIRD_PARTY_LICENSES.txt'),
  `Third-party packages bundled into plugin/server.mjs\n\n${sections.join('\n')}`
);
