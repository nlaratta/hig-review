export function ruleById(id: string): Rule | undefined {
  return RULES.find((r) => r.id === id);
}

export function appliesTo(rule: Rule, platform: ApplePlatform | undefined): boolean {
  return !platform || rule.platforms === 'all' || rule.platforms.includes(platform);
}

/** The per-platform variant of a rule family, e.g. ruleFor('controls.size', 'macos'). iPadOS shares iOS rules. */
export function ruleFor(prefix: string, platform: ApplePlatform): Rule | undefined {
  return ruleById(`${prefix}.${platform}`) ?? (platform === 'ipados' ? ruleById(`${prefix}.ios`) : undefined);
}
