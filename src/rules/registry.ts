/**
 * Rule registry: the review rules hig-review ships.
 *
 * Every rule points at a live HIG page (`source.slug`) and a short locator phrase
 * (`source.phrase`) that was confirmed on that page when the rule was written. The phrase is only
 * used to find the sentence at runtime; the quote shown to users is always fetched from Apple.
 * `check` is our own paraphrase of what to look for, not Apple's wording.
 *
 * `npm run smoke` re-checks every phrase against the live site and fails on stale ones.
 */

